import { expect, test } from '@playwright/test'

test.skip(process.env.IRIS_E2E_WRITE !== '1', 'Use a fresh demo SQLite database for mutations')

test('a manager publishes, searches, edits and archives an article', async ({ page }) => {
  const login = await page.request.post('/api/v1/auth/login', { data: { username: 'manager', password: 'iris-manager' } })
  expect(login.ok()).toBeTruthy()
  await page.goto('/manager')
  await page.getByRole('link', { name: 'База знаний', exact: true }).click()
  await page.getByRole('link', { name: 'Создать статью' }).click()
  const title = 'Условия тестового тарифа ' + Date.now()
  await page.getByLabel('Название').fill(title)
  await page.getByLabel('Текст статьи').fill('Подключение в течение недели.')
  await page.getByRole('button', { name: 'Сохранить черновик' }).click()
  await expect(page.getByText('Черновик', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Опубликовать' }).click()
  await expect(page.getByText('Статья опубликована', { exact: true })).toBeVisible()
  await page.getByLabel('Текст статьи').fill('Подключение в течение трёх дней.')
  await page.getByRole('button', { name: 'Сохранить изменения' }).click()
  await expect(page.getByText(/У статьи есть неопубликованные правки/)).toBeVisible()
  await page.getByRole('link', { name: 'К списку статей' }).click()
  await page.getByRole('searchbox', { name: 'Поиск по статьям' }).fill(title)
  await page.getByLabel('Категория').selectOption('company')
  await page.getByLabel('Статус').selectOption('published')
  await page.getByRole('link', { name: title, exact: true }).click()
  await expect(page.getByLabel('Текст статьи')).toHaveValue('Подключение в течение трёх дней.')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Архивировать' }).click()
  await expect(page.getByText('Статья в архиве', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'К списку статей' }).click()
  await expect(page.getByText('Статьи не найдены')).toBeVisible()
  await page.getByLabel('Статус').selectOption('archived')
  await expect(page.getByRole('link', { name: title, exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.getByRole('link', { name: title, exact: true }).click()
  await expect(page.getByLabel('Текст статьи')).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('an operator cannot open the knowledge base', async ({ page }) => {
  const login = await page.request.post('/api/v1/auth/login', { data: { username: 'operator', password: 'iris-operator' } })
  expect(login.ok()).toBeTruthy()
  await page.goto('/manager/knowledge')
  await expect(page).toHaveURL(new URL('/operator', page.url()).href)
  await expect(page.getByRole('navigation', { name: 'Разделы IRIS' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'База знаний', exact: true })).toHaveCount(0)
})
